export function getLessonBySlug(slug: string): Lesson | undefined {
  return LESSONS.find((l) => l.slug === slug);
}

export function getLessonsByTags(tags: string[]): Lesson[] {
  if (tags.length === 0) return LESSONS;
  return LESSONS.filter(
    (l) => l.contextTags.some((t) => tags.includes(t))
  ).sort((a, b) => {
    const aMatches = a.contextTags.filter((t) => tags.includes(t)).length;
    const bMatches = b.contextTags.filter((t) => tags.includes(t)).length;
    return bMatches - aMatches;
  });
}

const LEVEL_ORDER: Record<string, number> = {
  A1: 1,
  A2: 2,
  B1: 3,
  B2: 4,
  C1: 5,
  C2: 6,
};

export function getRecommendedLesson(
  estimatedLevel: string,
  interests: string[]
): Lesson {
  const levelValue = LEVEL_ORDER[estimatedLevel] ?? 1;
  const candidates = getLessonsByTags(interests).filter((l) => {
    const lessonLevel = LEVEL_ORDER[l.level] ?? 1;
    return lessonLevel >= levelValue - 1 && lessonLevel <= levelValue + 1;
  });
  return candidates[0] ?? LESSONS[0];
}
